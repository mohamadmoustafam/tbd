let mStarted = false,
  mBus,
  nextT = 0,
  stp = 0;
function tone(f, t, dur, vol, type) {
  const c = AC,
    o = c.createOscillator(),
    g = c.createGain();
  o.type = type;
  o.frequency.value = f;
  g.gain.setValueAtTime(0, t);
  g.gain.linearRampToValueAtTime(vol, t + 0.01);
  g.gain.exponentialRampToValueAtTime(0.001, t + dur);
  o.connect(g);
  g.connect(mBus);
  o.start(t);
  o.stop(t + dur + 0.05);
}
function note(t) {
  const ch = CHORDS[Math.floor(stp / 8) % 4],
    k = stp % 8;
  if (k === 0) tone(ch[0] / 2, t, 3.2, 0.45, "sine");
  const i = [1, 2, 3, 2, 4, 3, 5, 3][k];
  if (k % 2 === 0 || Math.random() < 0.5)
    tone(
      ch[Math.random() < 0.2 ? Math.min(i + 1, 5) : i],
      t,
      1.7,
      0.2,
      "triangle",
    );
  stp++;
}
function startMusic() {
  if (mStarted) return;
  mStarted = true;
  const c = ac();
  mBus = c.createGain();
  mBus.gain.value = 0;
  mBus.gain.linearRampToValueAtTime(muted ? 0 : 0.3, c.currentTime + 3);
  const dl = c.createDelay(1),
    fb = c.createGain(),
    lp = c.createBiquadFilter();
  dl.delayTime.value = 0.38;
  fb.gain.value = 0.38;
  lp.type = "lowpass";
  lp.frequency.value = 2200;
  mBus.connect(c.destination);
  mBus.connect(dl);
  dl.connect(lp);
  lp.connect(fb);
  fb.connect(dl);
  lp.connect(c.destination);
  nextT = c.currentTime + 0.2;
  setInterval(() => {
    while (nextT < c.currentTime + 1.5) {
      note(nextT);
      nextT += 0.42;
    }
  }, 250);
}
